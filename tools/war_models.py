def resample(flat, n=SAMPLES):
    p = [(flat[i + 1], flat[i]) for i in range(0, len(flat), 2)]      # (lon, lat)
    d = [0.0]
    for a, b in zip(p, p[1:]):
        d.append(d[-1] + math.hypot(b[0] - a[0], b[1] - a[1]))
    total = d[-1] or 1.0
    out, j = [], 0
    for i in range(n):
        t = total * i / (n - 1)
        while j < len(p) - 2 and d[j + 1] < t:
            j += 1
        span = d[j + 1] - d[j] or 1.0
        u = min(1.0, max(0.0, (t - d[j]) / span))
        out.append((p[j][0] + (p[j + 1][0] - p[j][0]) * u, p[j][1] + (p[j + 1][1] - p[j][1]) * u))
    return out


def line_at(front, day):
    import datetime
    keys = [(datetime.date.fromisoformat(d), p) for d, p in front["keys"]]
    if day < keys[0][0]:
        return None
    if front.get("until") and day >= datetime.date.fromisoformat(front["until"]):
        return None
    i = max(k for k in range(len(keys)) if keys[k][0] <= day)
    if i >= len(keys) - 1:
        return resample(keys[-1][1])
    a, b = resample(keys[i][1]), resample(keys[i + 1][1])
    t = (day - keys[i][0]).days / max(1, (keys[i + 1][0] - keys[i][0]).days)
    return [(x1 + (x2 - x1) * t, y1 + (y2 - y1) * t) for (x1, y1), (x2, y2) in zip(a, b)]


def half(line, kind):
    first, last = line[0], line[-1]
    if kind == "W":
        return line + [(last[0], -80), (-179, -80), (-179, 84), (first[0], 84)]
    if kind == "E":
        return line + [(last[0], -80), (179, -80), (179, 84), (first[0], 84)]
    if kind == "S":
        return line + [(179, last[1]), (179, -80), (-179, -80), (-179, first[1])]
    if kind == "N":
        return line + [(179, last[1]), (179, 84), (-179, 84), (-179, first[1])]
    return line


def preview(directory, shots):
    import datetime
    from PIL import Image, ImageDraw, ImageChops
    os.makedirs(directory, exist_ok=True)
    for name, box, dates in shots:
        model = MODELS[name]
        base = json.load(open(os.path.join(OUT, model["base"] + ".json"), encoding="utf-8"))
        colors = {s["k"]: s["c"] for s in model["sides"]}
        lon0, lat0, lon1, lat1 = box
        my = lambda lat: math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))
        width = 900
        scale = width / (lon1 - lon0)
        k = scale * 180 / math.pi
        height = int((my(lat1) - my(lat0)) * k)
        xy = lambda lon, lat: ((lon - lon0) * scale, (my(lat1) - my(max(-84, min(84, lat)))) * k)
        for date in dates:
            day = datetime.date.fromisoformat(date)
            img = Image.new("RGB", (width, height), "#10141c")
            draw = ImageDraw.Draw(img)
            side = {}
            for region in base["regions"]:
                state = None
                for d, s in model["rules"].get(region["n"], []):
                    if datetime.date.fromisoformat(d) <= day:
                        state = s
                side[region["n"]] = state
                for ring in region["r"]:
                    poly = [xy(ring[i] / 1000, ring[i + 1] / 1000) for i in range(0, len(ring), 2)]
                    draw.polygon(poly, fill=colors.get(state, "#232a36"), outline="#000000")
            for front in model["fronts"]:
                line = line_at(front, day)
                if not line:
                    continue
                mask_half = Image.new("L", (width, height), 0)
                ImageDraw.Draw(mask_half).polygon([xy(*p) for p in half(line, front["half"])], fill=255)
                for region in base["regions"]:
                    if region["n"] not in front["regions"] or side[region["n"]] not in front["targets"]:
                        continue
                    mask_region = Image.new("L", (width, height), 0)
                    for ring in region["r"]:
                        ImageDraw.Draw(mask_region).polygon(
                            [xy(ring[i] / 1000, ring[i + 1] / 1000) for i in range(0, len(ring), 2)], fill=255)
                    img.paste(colors[front["a"]], mask=ImageChops.multiply(mask_region, mask_half))
                    if front["b"]:
                        img.paste(colors[front["b"]], mask=ImageChops.multiply(mask_region, ImageChops.invert(mask_half)))
                ImageDraw.Draw(img).line([xy(*p) for p in line] + ([xy(*line[0])] if front["half"] == "POLY" else []),
                                         fill="#ffd84a", width=2)
            ImageDraw.Draw(img).text((8, 6), "%s  %s" % (name, date), fill="#ffffff")
            img.save(os.path.join(directory, "%s_%s.png" % (name, date)))


